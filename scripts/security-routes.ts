/**
 * The Control API's route-authorisation table, read from the routes the app serves and not from the
 * documentation: `bun run security:routes` prints it, `--write` rewrites docs/security/routes.md and
 * `--check` fails when that file is stale. `packages/control-api/test/security.routes.test.ts` holds
 * every row to the behaviour it states.
 */
import { join } from 'node:path';
import { createControlApi } from '../packages/control-api/src';
import type { Access } from '../packages/control-api/src/http/router';
import type { PostgresStore } from '../packages/store-postgres/src';
import { MemoryTransport } from '../packages/transport-local/src';

export type Who = 'public' | 'any' | 'operator';

export interface Row {
  readonly method: string;
  readonly path: string;
  readonly who: Who;
}

const WHO: Record<Who, string> = {
  public: 'anyone, no token',
  any: 'viewer or operator',
  operator: 'operator only',
};

const whoOf = ({ access, operatorOnly }: { access: Access; operatorOnly?: true }): Who =>
  access === 'public' ? 'public' : access === 'write' || operatorOnly ? 'operator' : 'any';

/** Every route a full build serves. A stub store is enough: the table needs the routes, not their handlers. */
export function routeTable(): Row[] {
  const app = createControlApi(
    {
      version: 'security-routes',
      production: false,
      devToken: { token: 'x'.repeat(32) },
      logger: { request() {}, error() {}, warn() {} },
    },
    {
      transport: { name: 'memory', capabilities: new MemoryTransport().capabilities },
      readiness: {
        database: async () => {},
        transport: () => 'ok',
        tick: async () => null,
      },
      jobs: { store: {} as PostgresStore, transport: new MemoryTransport() },
    },
    {}
  );
  return app.routes
    .map((route) => ({ method: route.method, path: route.path, who: whoOf(route) }))
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

export function renderRoutes(rows: readonly Row[] = routeTable()): string {
  const count = (who: Who) => rows.filter((row) => row.who === who).length;
  return [
    '<!-- Generated by `bun run security:routes --write` from the routes the Control API serves. Do not edit. -->',
    '# Control API: who may call what',
    '',
    `${rows.length} routes: ${count('public')} public, ${count('any')} for any authenticated principal, ${count('operator')} for an operator. A viewer is refused every`,
    'operator route with 403 `forbidden`; a missing or invalid token is 401 on every route but `GET /health`.',
    'Held row by row by `packages/control-api/test/security.routes.test.ts`.',
    '',
    '| Method | Path | Who may call |',
    '| --- | --- | --- |',
    ...rows.map((row) => `| ${row.method} | \`${row.path}\` | ${WHO[row.who]} |`),
    '',
  ].join('\n');
}

if (import.meta.main) {
  const file = join(import.meta.dir, '../docs/security/routes.md');
  const text = renderRoutes();
  if (process.argv.includes('--write')) await Bun.write(file, text);
  else if (process.argv.includes('--check')) {
    if ((await Bun.file(file).text().catch(() => '')) !== text) {
      console.error('docs/security/routes.md is stale: run `bun run security:routes --write`');
      process.exit(1);
    }
  } else console.log(text);
}
